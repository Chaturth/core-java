package Programs;

public class MathFunctions {
    public static void main(String[] args) {

        System.out.println(Math.abs(-20)); //it makes negative number as positive

        System.out.println(Math.round(10.6)); //it makes decimal number to a nearest whole number

        System.out.println(Math.ceil(12.2)); //it makes decimal number to upward whole number

        System.out.println(Math.floor(10.8)); //it makes decimal number to downward whole number

        System.out.println(Math.sqrt(16));

        System.out.println(Math.max(10,12));

        System.out.println(Math.min(33,44));

        System.out.println(Math.pow(2,3));

        System.out.println(Math.random());

        System.out.println(Math.exp(10)); //e=2.718

        System.out.println(Math.sin(10));

        System.out.println(Math.cos(10));

        System.out.println(Math.tan(10));

        System.out.println(Math.log(10));
    }
}
